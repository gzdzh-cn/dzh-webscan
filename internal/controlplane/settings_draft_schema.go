package controlplane

// v3_settings remains the live policy read by workers. An ordinary edit or
// restore candidate has a separate generation, and never becomes live by save.
// No draft row means the legacy live policy is also the saved baseline.
const settingsDraftSchema = `
CREATE TABLE v3_settings_drafts(
 id integer PRIMARY KEY CHECK(id=1),
 generation bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE CHECK(generation>0),
 runtime_version bigint NOT NULL CHECK(runtime_version>0),runtime_digest text NOT NULL,
 applied_generation bigint NOT NULL DEFAULT 0 CHECK(applied_generation>=0 AND applied_generation<=generation),
 payload jsonb NOT NULL CHECK(jsonb_typeof(payload)='object'),proof text NOT NULL,
 updated_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
INSERT INTO v3_schema(version) VALUES(20);
`
