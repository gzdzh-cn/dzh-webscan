func currentSchema(ctx context.Context, db interface {
	QueryRowContext(context.Context, string, ...any) *sql.Row
}) (int, error) {
	var exists bool
	if err := db.QueryRowContext(ctx, "SELECT to_regclass(current_schema()||'.v3_schema') IS NOT NULL").Scan(&exists); err != nil {
		return 0, err
	}
	if !exists {
		return 0, nil
	}
	var version int
	err := db.QueryRowContext(ctx, "SELECT COALESCE(max(version),0) FROM v3_schema").Scan(&version)
	return version, err
}
