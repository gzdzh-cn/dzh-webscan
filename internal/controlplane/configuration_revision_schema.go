package controlplane

// A saved restore candidate is not a live configuration. Its generation is
// independent of the versions in the active settings/node tables. Terminal
// references remain historical metadata; protection is held by the stage pins.
const configurationRevisionSchema = `
ALTER TABLE v3_configuration_restore_stages
 DROP CONSTRAINT v3_configuration_restore_stages_status_check,
 DROP CONSTRAINT v3_configuration_restore_stages_check1;
ALTER TABLE v3_configuration_restore_stages
 ADD CONSTRAINT v3_configuration_restore_stages_status_check CHECK(status IN ('pending_validation','pending_application','cancelled')),
 ADD CONSTRAINT v3_configuration_restore_stages_check1 CHECK((status IN ('pending_validation','pending_application') AND finished_at IS NULL) OR (status='cancelled' AND finished_at IS NOT NULL));
DROP INDEX v3_configuration_restore_one_pending;
CREATE UNIQUE INDEX v3_configuration_restore_one_pending ON v3_configuration_restore_stages((true)) WHERE status IN ('pending_validation','pending_application');
CREATE TABLE v3_configuration_revisions(
 id text PRIMARY KEY,generation bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
 stage text NOT NULL UNIQUE,username text NOT NULL,account_revision bigint NOT NULL CHECK(account_revision>0),
 base_settings_version bigint NOT NULL CHECK(base_settings_version>0),
 status text NOT NULL DEFAULT 'pending_application' CHECK(status IN ('pending_application','cancelled')),
 message text NOT NULL DEFAULT '恢复配置已保存，待应用；运行配置未修改',
 document_created_at text NOT NULL,node_count integer NOT NULL CHECK(node_count BETWEEN 0 AND 20000),
 candidate_proof text NOT NULL,state_proof text NOT NULL,key_id text NOT NULL,nonce bytea NOT NULL,
 ciphertext_bytes integer NOT NULL CHECK(ciphertext_bytes BETWEEN 17 AND 33554448),
 created_at timestamptz NOT NULL DEFAULT clock_timestamp(),updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),finished_at timestamptz,
 CHECK(generation>0),
 CHECK((status='pending_application' AND finished_at IS NULL) OR (status='cancelled' AND finished_at IS NOT NULL))
);
CREATE UNIQUE INDEX v3_configuration_one_pending_revision ON v3_configuration_revisions((true)) WHERE status='pending_application';
CREATE INDEX v3_configuration_revision_history ON v3_configuration_revisions(created_at DESC,id DESC);
CREATE INDEX v3_configuration_revision_expiry ON v3_configuration_revisions(finished_at,id) WHERE status='cancelled';
CREATE TABLE v3_configuration_revision_parts(
 revision text NOT NULL REFERENCES v3_configuration_revisions(id) ON DELETE CASCADE,
 part integer NOT NULL CHECK(part BETWEEN 0 AND 32),payload bytea NOT NULL CHECK(octet_length(payload) BETWEEN 1 AND 1048576),
 PRIMARY KEY(revision,part)
);
INSERT INTO v3_schema(version) VALUES(18);
`
