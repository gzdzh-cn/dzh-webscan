package controlplane

const manualHistorySchema = `
CREATE TABLE v3_history_gates(username text PRIMARY KEY,version bigint NOT NULL);
CREATE TABLE v3_history_previews(
 id text PRIMARY KEY,username text NOT NULL,settings_version bigint NOT NULL,
 scope jsonb NOT NULL,cutoff timestamptz NOT NULL,created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 expires_at timestamptz NOT NULL DEFAULT clock_timestamp()+interval '10 minutes',
 used boolean NOT NULL DEFAULT false,eligible bigint NOT NULL DEFAULT 0,protected bigint NOT NULL DEFAULT 0
);
CREATE INDEX v3_history_preview_expiry ON v3_history_previews(expires_at,id);
CREATE INDEX v3_history_preview_owner ON v3_history_previews(username,expires_at) WHERE NOT used;
CREATE TABLE v3_history_items(
 ordinal bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 preview text NOT NULL REFERENCES v3_history_previews(id),
 stage integer NOT NULL CHECK(stage BETWEEN 0 AND 6),node text NOT NULL,id text NOT NULL,
 stamp timestamptz NOT NULL,eligible boolean NOT NULL,
 exported boolean NOT NULL DEFAULT false,export_part text NOT NULL DEFAULT '',done boolean NOT NULL DEFAULT false,
 UNIQUE(preview,stage,node,id,stamp)
);
CREATE INDEX v3_history_items_preview ON v3_history_items(preview,ordinal);
CREATE INDEX v3_history_items_pending ON v3_history_items(preview,ordinal) WHERE NOT done;
CREATE INDEX v3_history_items_identity ON v3_history_items(stage,node,id,stamp,preview);
CREATE TABLE v3_history_jobs(
 id text PRIMARY KEY,username text NOT NULL,preview text NOT NULL UNIQUE REFERENCES v3_history_previews(id),
 kind text NOT NULL CHECK(kind IN ('export','cleanup')),export_first boolean NOT NULL,
 settings_version bigint NOT NULL,cutoff timestamptz NOT NULL,
 phase text NOT NULL CHECK(phase IN ('export','cleanup','finished')),
 status text NOT NULL DEFAULT 'queued' CHECK(status IN ('queued','running','succeeded','partial','cancelled','failed')),
 cursor bigint NOT NULL DEFAULT 0,export_cursor bigint NOT NULL DEFAULT 0,
 scanned bigint NOT NULL DEFAULT 0,deleted bigint NOT NULL DEFAULT 0,skipped bigint NOT NULL DEFAULT 0,
 dependent_deleted bigint NOT NULL DEFAULT 0,exported bigint NOT NULL DEFAULT 0,
 export_bytes bigint NOT NULL DEFAULT 0,export_ready boolean NOT NULL DEFAULT false,
 export_expires_at timestamptz,message text NOT NULL DEFAULT '',
 created_at timestamptz NOT NULL DEFAULT clock_timestamp(),updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),finished_at timestamptz
);
CREATE INDEX v3_history_jobs_pending ON v3_history_jobs(created_at,id) WHERE status IN ('queued','running');
CREATE INDEX v3_history_jobs_owner ON v3_history_jobs(username,created_at DESC,id DESC);
CREATE INDEX v3_history_jobs_export_expiry ON v3_history_jobs(export_expires_at) WHERE export_ready;
CREATE TABLE v3_history_export_parts(
 id text PRIMARY KEY,job text NOT NULL REFERENCES v3_history_jobs(id),ordinal bigint NOT NULL,
 bytes bigint NOT NULL DEFAULT 0,sha256 text NOT NULL DEFAULT '',ready boolean NOT NULL DEFAULT false,
 created_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE UNIQUE INDEX v3_history_parts_order ON v3_history_export_parts(job,ordinal) WHERE ready;
CREATE INDEX v3_history_parts_job ON v3_history_export_parts(job);
INSERT INTO v3_schema(version) VALUES(11);
`
