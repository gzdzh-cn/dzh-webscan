type AuditRecord struct {
	ID           string         `json:"id"`
	Username     string         `json:"username"`
	Kind         string         `json:"kind"`
	Resource     string         `json:"resource"`
	Result       map[string]any `json:"result"`
	Created      time.Time      `json:"created_at"`
	RecordKey    string         `json:"record_key"`
	CanDelete    bool           `json:"can_delete"`
	DeleteReason string         `json:"delete_reason"`
}

// Audit schemas evolve independently of clients. Expose a typed summary, never
// arbitrary imported JSON, provider messages, file paths or preview tokens.
func publicAuditResult(raw []byte) map[string]any {
	decoder := json.NewDecoder(bytes.NewReader(raw))
	decoder.UseNumber()
	var input map[string]any
	if decoder.Decode(&input) != nil {
		return map[string]any{"details_unavailable": true}
	}
	out := map[string]any{}
	for _, key := range []string{"scanned", "deleted", "protected", "dependent_deleted", "skipped", "failed", "exported", "export_bytes", "settings_version", "eligible", "selected", "processed", "count", "stage", "added", "updated", "unchanged", "version"} {
		if value, ok := input[key].(json.Number); ok {
			if n, err := value.Int64(); err == nil && n >= 0 {
				out[key] = value
			}
		}
	}
	for _, key := range []string{"shortened", "completed", "continuing_dependencies", "complete", "ready_for_cutover", "download_available"} {
		if value, ok := input[key].(bool); ok {
			out[key] = value
		}
	}
	if value, ok := input["status"].(string); ok {
		switch value {
		case "queued", "running", "succeeded", "partial", "cancelled", "failed", "complete":
			out["status"] = value
		}
	}
	if value, ok := input["phase"].(string); ok {
		switch value {
		case "export", "cleanup", "finished":
			out["phase"] = value
		}
	}
	if value, ok := input["operation"].(string); ok {
		switch value {
		case "website", "website-backup", "deployment-backup", "deployment-job", "cleanup", "export":
			out["operation"] = value
		}
	}
	// Legacy identity is audit evidence; it never authorizes a new operation.
	for _, key := range []string{"legacy_id", "legacy_table", "migration_source"} {
		if value, ok := input[key].(string); ok && eventText(value, 128) {
			out[key] = value
		}
	}
	if scope, ok := input["scope"].(map[string]any); ok {
		summary := map[string]any{}
		if categories, ok := scope["categories"].([]any); ok && len(categories) <= 6 {
			safe := []string{}
			for _, c := range categories {
				if v, ok := c.(string); ok {
					switch v {
					case "events", "security-events", "website-incidents", "server-alerts", "feishu", "email":
						safe = append(safe, v)
					}
				}
			}
			summary["categories"] = safe
		}
		if node, ok := scope["node"].(string); ok && eventText(node, 512) {
			summary["node"] = node
		}
		if before, ok := scope["before"].(string); ok {
			if at, err := time.Parse(time.RFC3339Nano, before); err == nil && validAuditTime(at) {
				summary["before"] = before
			}
		}
		if probes, ok := scope["include_probes"].(bool); ok {
			summary["include_probes"] = probes
		}
		if records, ok := scope["records"].([]any); ok {
			summary["selected"] = len(records)
		}
		out["scope"] = summary
	}
	// These summaries are generated by the validated legacy mapper, but enforce
	// scalar types again rather than trusting a nested result object forever.
	if scopes, ok := input["scope_summary"].([]any); ok && len(scopes) <= 20 {
		safe := []map[string]any{}
		for _, scope := range scopes {
			v, ok := scope.(map[string]any)
			if !ok {
				continue
			}
			row := map[string]any{}
			if source, ok := v["source"].(string); ok {
				switch source {
				case "events", "security", "migrated_events", "migrated_security", "website", "server", "notifications", "notification_orphans", "server_batches":
					row["source"] = source
				}
			}
			if node, ok := v["node"].(string); ok && eventText(node, 512) {
				row["node"] = node
			}
			for _, key := range []string{"before", "upper", "selected"} {
				if n, ok := v[key].(json.Number); ok {
					if value, err := n.Int64(); err == nil && value >= 0 {
						row[key] = n
					}
				}
			}
			safe = append(safe, row)
		}
		out["scope_summary"] = safe
	}
	return out
}

func (s *Store) AuditHistory(ctx context.Context, user, role, actor, kind string, start, end time.Time, before notificationCursor, limit int) ([]AuditRecord, error) {
	if limit < 1 || limit > 200 || !validAuditTime(start) || !validAuditTime(end) || !end.After(start) || end.Sub(start) > 31*24*time.Hour || (actor != "" && !eventText(actor, 128)) || (kind != "" && !eventText(kind, 128)) {
		return nil, ErrHistoryInput
	}
	if role != "admin" && role != "operator" && role != "viewer" {
		return nil, errors.New("审计读取权限不正确")
	}
	if before.Time.IsZero() {
		before.Time = time.Date(9999, 1, 1, 0, 0, 0, 0, time.UTC)
		before.ID = "1"
	}
	rows, err := s.DB.QueryContext(ctx, `SELECT id::text,username,kind,resource,result,created_at FROM v3_audit WHERE ($1='admin' OR username=$2 OR username='system') AND ($3='' OR username=$3) AND ($4='' OR kind=$4) AND created_at>=$5 AND created_at<=$6 AND (created_at,id)<($7,$8::bigint) ORDER BY created_at DESC,id DESC LIMIT $9`, role, user, actor, kind, start, end, before.Time, before.ID, limit)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	out := []AuditRecord{}
	for rows.Next() {
		var v AuditRecord
		var raw []byte
		if err = rows.Scan(&v.ID, &v.Username, &v.Kind, &v.Resource, &raw, &v.Created); err != nil {
			return nil, err
		}
		v.Result = publicAuditResult(raw)
		v.RecordKey = "audit:" + v.ID
		v.DeleteReason = "审计只读，按 365 天期限保留"
		out = append(out, v)
	}
	return out, rows.Err()
}
func (a *API) auditRoutes(w http.ResponseWriter, r *http.Request, id identity) bool {
	if r.URL.Path != "/api/v3/audit" {
		return false
	}
	if r.Method != "GET" {
		failure(w, 405, "method_not_allowed", "审计只读，不支持删除或修改")
		return true
	}
	start, end, err := timeRange(r)
	if err != nil {
		failure(w, 400, "invalid_time", "时间范围不正确，最多 31 天")
		return true
	}
	limit, err := pageSize(r, 20)
	if err != nil {
		failure(w, 400, "invalid_limit", err.Error())
		return true
	}
	before, err := decodeNotificationCursor(r.URL.Query().Get("cursor"))
	if err != nil {
		failure(w, 400, "invalid_cursor", "审计分页游标不正确")
		return true
	}
	ctx, cancel := context.WithTimeout(r.Context(), 10*time.Second)
	defer cancel()
	items, err := a.Store.AuditHistory(ctx, id.Username, id.Role, r.URL.Query().Get("actor"), r.URL.Query().Get("kind"), start, end, before, limit)
	if err != nil {
		historyFailure(w, err)
		return true
	}
	next := ""
	if len(items) == limit {
		v := items[len(items)-1]
		next = (notificationCursor{v.Created, v.ID}).encode()
	}
	reply(w, 200, map[string]any{"items": items, "next_cursor": next, "start": start, "end": end, "limit": limit})
	return true
}
