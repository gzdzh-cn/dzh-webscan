package controlplane

// Restoring into the saved configuration is distinct from runtime application.
// Startup drafts belong to a stable member identity, not a process lease ID.
const configurationSavedSchema = `
CREATE TABLE v3_bootstrap_drafts(
 instance text PRIMARY KEY,generation bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE CHECK(generation>0),
 applied_generation bigint NOT NULL DEFAULT 0 CHECK(applied_generation>=0 AND applied_generation<=generation),
 runtime_digest text NOT NULL,payload jsonb NOT NULL CHECK(jsonb_typeof(payload)='object'),proof text NOT NULL,
 updated_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
ALTER TABLE v3_configuration_restore_stages
 DROP CONSTRAINT v3_configuration_restore_stages_status_check,
 DROP CONSTRAINT v3_configuration_restore_stages_check1;
ALTER TABLE v3_configuration_restore_stages
 ADD CONSTRAINT v3_configuration_restore_stages_status_check CHECK(status IN ('pending_validation','pending_application','saved','cancelled')),
 ADD CONSTRAINT v3_configuration_restore_stages_check1 CHECK((status IN ('pending_validation','pending_application') AND finished_at IS NULL) OR (status IN ('saved','cancelled') AND finished_at IS NOT NULL));
ALTER TABLE v3_configuration_revisions
 DROP CONSTRAINT v3_configuration_revisions_status_check,
 DROP CONSTRAINT v3_configuration_revisions_check;
ALTER TABLE v3_configuration_revisions
 ADD CONSTRAINT v3_configuration_revisions_status_check CHECK(status IN ('pending_application','saved','cancelled')),
 ADD CONSTRAINT v3_configuration_revisions_check CHECK((status='pending_application' AND finished_at IS NULL) OR (status IN ('saved','cancelled') AND finished_at IS NOT NULL));
CREATE TABLE v3_configuration_restore_commits(
 stage text PRIMARY KEY,revision text NOT NULL UNIQUE REFERENCES v3_configuration_revisions(id),
 username text NOT NULL,account_revision bigint NOT NULL CHECK(account_revision>0),
 result jsonb NOT NULL CHECK(jsonb_typeof(result)='object'),deployments jsonb NOT NULL,
 archives jsonb NOT NULL CHECK(jsonb_typeof(archives)='array' AND jsonb_array_length(archives)=2),proof text NOT NULL,
 created_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
INSERT INTO v3_schema(version) VALUES(21);
`
