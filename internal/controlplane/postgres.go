var ErrConflict = errors.New("配置版本冲突，请重新加载")
var ErrLeaseLost = errors.New("采集租约已失效")
var identifier = regexp.MustCompile(`^[a-zA-Z0-9][a-zA-Z0-9_.-]{0,127}$`)

type Store struct {
	DB              *sql.DB
	ExportDirectory string
	HostQuota       *HostQuotaClient
}

func Open(ctx context.Context, c Config) (*Store, error) {
	dsn, e := ReadSecret(c.Database.DSNFile)
	if e != nil {
		return nil, e
	}
	return openConfiguredDSN(ctx, c, dsn)
}

func openConfiguredDSN(ctx context.Context, c Config, dsn string) (*Store, error) {
	db, e := sql.Open("pgx", dsn)
	if e != nil {
		return nil, errors.New("数据库配置无效")
	}
	db.SetMaxOpenConns(c.Database.MaxConnections)
	db.SetMaxIdleConns(c.Database.MaxConnections)
	db.SetConnMaxLifetime(30 * time.Minute)
	ping, cancel := context.WithTimeout(ctx, 10*time.Second)
	defer cancel()
	if e = db.PingContext(ping); e != nil {
		db.Close()
		return nil, errors.New("PostgreSQL 无法访问，请检查网络及凭据文件")
	}
	quota, err := newHostQuotaClient(c)
	if err != nil {
		db.Close()
		return nil, err
	}
	return &Store{DB: db, ExportDirectory: c.Central.ExportDirectory, HostQuota: quota}, nil
}

