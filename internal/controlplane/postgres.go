func Shard(id string, n int) int {
	h := fnv.New32a()
	_, _ = h.Write([]byte(id))
	return int(h.Sum32() % uint32(n))
}
func (n Node) Validate() error {
	if !identifier.MatchString(n.ID) || strings.TrimSpace(n.Name) == "" || len(n.Name) > 256 {
		return errors.New("节点编号或名称不正确")
	}
	h, p, e := net.SplitHostPort(n.Endpoint)
	if e != nil || h == "" || p == "" {
		return errors.New("节点 endpoint 必须为主机:端口")
	}
	port, e := strconv.Atoi(p)
	if e != nil || port < 1 || port > 65535 {
		return errors.New("节点端口不正确")
	}
	if len(h) > 253 || strings.ContainsAny(h, "/\\?#@\x00\r\n \t") {
		return errors.New("节点主机地址不正确")
	}
	if n.ServerName == "" || len(n.ServerName) > 253 || strings.ContainsAny(n.ServerName, "/\\\x00\r\n \t") {
		return errors.New("节点 TLS 身份必填")
	}
	if n.Mode != "native" && n.Mode != "docker" {
		return errors.New("部署方式只允许 native 或 docker")
	}
	return nil
}
func scanNode(row interface{ Scan(...any) error }) (n Node, e error) {
	e = row.Scan(&n.ID, &n.Name, &n.Endpoint, &n.ServerName, &n.Enabled, &n.Mode, &n.Version, &n.AppliedVersion, &n.Shard, &n.Config)
	if e == nil {
		n.Monitoring = monitoringForNode(n)
	}
	return
}

const nodeColumns = "id,name,endpoint,server_name,enabled,mode,version,applied_version,shard,config"

func (s *Store) Nodes(ctx context.Context, after, keyword string, limit int, shard *int) ([]Node, error) {
	if limit < 1 || limit > 200 {
		return nil, errors.New("每页数量须为 1～200")
	}
	q := "SELECT " + managedNodeColumns + " FROM " + managedNodeRelations + ` WHERE n.id>$1 AND (n.name ILIKE $2 ESCAPE '\' OR n.id ILIKE $2 ESCAPE '\')`
	args := []any{after, "%" + strings.NewReplacer("\\", "\\\\", "%", "\\%", "_", "\\_").Replace(keyword) + "%"}
	if shard != nil {
		q = "SELECT " + activeNodeColumns + ` FROM v3_active_nodes WHERE id>$1 AND (name ILIKE $2 ESCAPE '\' OR id ILIKE $2 ESCAPE '\')`
		q += " AND enabled AND shard=$3"
		args = append(args, *shard)
	}
	if shard == nil {
		q += fmt.Sprintf(" ORDER BY n.id LIMIT $%d", len(args)+1)
	} else {
		q += fmt.Sprintf(" ORDER BY id LIMIT $%d", len(args)+1)
	}
	args = append(args, limit)
	rows, e := s.DB.QueryContext(ctx, q, args...)
	if e != nil {
		return nil, e
	}
	defer rows.Close()
	out := []Node{}
	for rows.Next() {
		var n Node
		var e error
		if shard != nil {
			n, e = scanActiveNode(rows)
		} else {
			n, e = scanManagedNode(rows)
		}
		if e != nil {
			return nil, e
		}
		out = append(out, n)
	}
	return out, rows.Err()
}
func (s *Store) PutNode(ctx context.Context, n Node, expected int64, shards int) error {
	// Trusted setup explicitly registers an existing collector target. Public
	// edits use saveNode and only change desired state.
	tx, err := s.DB.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer tx.Rollback()
	if err = lockDeploymentWriteRelationsTx(ctx, tx); err != nil {
		return err
	}
	if err = checkMonitoringNodeReservationTx(ctx, tx, n.ID); err != nil {
		return err
	}
	if err = putNode(ctx, tx, n, expected, shards); err != nil {
		return err
	}
	snapshot, err := captureSavedNodeTx(ctx, tx, n.ID)
	if err != nil {
		return err
	}
	if err = publishNodeRuntimeTx(ctx, tx, n.ID, snapshot, n.AppliedVersion); err != nil {
		return err
	}
	return tx.Commit()
}

type sqlExecutor interface {
	ExecContext(context.Context, string, ...any) (sql.Result, error)
}

func putNode(ctx context.Context, db sqlExecutor, n Node, expected int64, shards int) error {
	if e := n.Validate(); e != nil {
		return e
	}
	if shards < 1 || shards > 4096 {
		return errors.New("分片数不正确")
	}
	if len(n.Config) == 0 && expected == 0 {
		n.Config = json.RawMessage(`{}`)
	}
	var configArg any
	if len(n.Config) > 0 {
		var object map[string]json.RawMessage
		if json.Unmarshal(n.Config, &object) != nil || object == nil {
			return errors.New("节点配置必须为 JSON 对象")
		}
		configArg = []byte(n.Config)
	}
	if expected == 0 {
		r, e := db.ExecContext(ctx, "INSERT INTO v3_nodes(id,name,endpoint,server_name,enabled,mode,shard,config) VALUES($1,$2,$3,$4,$5,$6,$7,$8) ON CONFLICT DO NOTHING", n.ID, n.Name, n.Endpoint, n.ServerName, n.Enabled, n.Mode, Shard(n.ID, shards), configArg)
		if e != nil {
			return e
		}
		v, _ := r.RowsAffected()
		if v != 1 {
			return ErrConflict
		}
		return nil
	}
	r, e := db.ExecContext(ctx, "UPDATE v3_nodes SET name=$1,endpoint=$2,server_name=$3,enabled=$4,mode=$5,config=COALESCE($6::jsonb,config),version=version+1,updated_at=clock_timestamp() WHERE id=$7 AND version=$8 AND removed_at IS NULL", n.Name, n.Endpoint, n.ServerName, n.Enabled, n.Mode, configArg, n.ID, expected)
	if e != nil {
		return e
	}
	v, _ := r.RowsAffected()
	if v != 1 {
		return ErrConflict
	}
	return nil
}

type Lease struct {
	Resource, Owner string
	Epoch           int64
	Expires         time.Time
}

func (s *Store) Acquire(ctx context.Context, resource, owner string) (Lease, error) {
	l := Lease{Resource: resource, Owner: owner}
	e := s.DB.QueryRowContext(ctx, `INSERT INTO v3_leases(resource,owner,epoch,expires_at) VALUES($1,$2,1,clock_timestamp()+interval '30 seconds') ON CONFLICT(resource) DO UPDATE SET owner=EXCLUDED.owner,epoch=CASE WHEN v3_leases.owner=EXCLUDED.owner AND v3_leases.expires_at>clock_timestamp() THEN v3_leases.epoch ELSE v3_leases.epoch+1 END,expires_at=clock_timestamp()+interval '30 seconds' WHERE v3_leases.owner=EXCLUDED.owner OR v3_leases.expires_at<=clock_timestamp() RETURNING epoch,expires_at`, resource, owner).Scan(&l.Epoch, &l.Expires)
	if e == sql.ErrNoRows {
		return l, ErrLeaseLost
	}
	return l, e
}
func (s *Store) Fence(ctx context.Context, tx *sql.Tx, l Lease) error {
	var epoch int64
	e := tx.QueryRowContext(ctx, "SELECT epoch FROM v3_leases WHERE resource=$1 AND owner=$2 AND epoch=$3 AND expires_at>clock_timestamp() FOR SHARE", l.Resource, l.Owner, l.Epoch).Scan(&epoch)
	if e == sql.ErrNoRows {
		return ErrLeaseLost
	}
	return e
}
func (s *Store) Release(ctx context.Context, l Lease) error {
	_, e := s.DB.ExecContext(ctx, "UPDATE v3_leases SET expires_at=clock_timestamp() WHERE resource=$1 AND owner=$2 AND epoch=$3", l.Resource, l.Owner, l.Epoch)
	return e
}

func digest(raw []byte) string { v := sha256.Sum256(raw); return hex.EncodeToString(v[:]) }
