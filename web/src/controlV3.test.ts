// @vitest-environment jsdom
import { afterEach, describe, expect, it, vi } from 'vitest'
import { ControlV3, V3Error } from './controlV3'

afterEach(() => { vi.unstubAllGlobals() })

describe('v3 transport contract', () => {
  it('submits only saved stage and exact string cursor with explicit retry keys', async () => {
    const fetcher = vi.fn().mockImplementation(async () => new Response('{}')); vi.stubGlobal('fetch', fetcher)
    const client = new ControlV3(), signal = new AbortController().signal, id = 'a'.repeat(64)
    await client.queueConfigurationApplication(id, '9007199254740993', 'queue-once', signal)
    await client.controlConfigurationApplication(id, 'rollback', '9007199254740995', 'control-once', signal)
    expect(JSON.parse(fetcher.mock.calls[0]![1].body)).toEqual({ stage: id, generation: '9007199254740993', confirm: true })
    expect(JSON.parse(fetcher.mock.calls[1]![1].body)).toEqual({ expected_log_cursor: '9007199254740995', confirm: true })
    expect(fetcher.mock.calls[1]![1].headers['Idempotency-Key']).toBe('control-once')
    for (const value of ['0', '01', '-1', '9223372036854775808']) expect(() => client.queueConfigurationApplication(id, value, 'bad')).toThrow('版本')
    expect(fetcher).toHaveBeenCalledTimes(2)
  })
  it('preserves application log bigint cursors and uses read calls for progress', async () => {
    const fetcher = vi.fn().mockImplementation(async () => new Response('{}')); vi.stubGlobal('fetch', fetcher)
    const client = new ControlV3(), id = 'a'.repeat(64), controller = new AbortController()
    await client.configurationApplications('b'.repeat(64), 'opaque', 20, controller.signal)
    await client.configurationApplication(id, controller.signal)
    await client.configurationApplicationLogs(id, '9007199254740993', 100, controller.signal)
    expect(fetcher.mock.calls[2]?.[0]).toBe(`/api/v3/configuration-applications/${id}/logs?after=9007199254740993&limit=100`)
    for (const call of fetcher.mock.calls) expect(call[1].method).toBe('GET')
    for (const invalid of ['-1', '1.5', '01', '9223372036854775808']) expect(() => client.configurationApplicationLogs(id, invalid)).toThrow('游标')
    expect(fetcher).toHaveBeenCalledTimes(3)
  })
  it('preserves restore generations, CSRF and idempotency keys across the saved-only workflow', async () => {
    const fetcher = vi.fn().mockImplementation(async () => new Response('{}')); vi.stubGlobal('fetch', fetcher)
    const client = new ControlV3(); fetcher.mockResolvedValueOnce(new Response('{"csrf":"restore-csrf"}')); await client.session(); fetcher.mockClear()
    const id = 'a'.repeat(64)
    await client.previewConfigurationRestore(id, false)
    await client.stageConfigurationRestore('b'.repeat(64), 'stage-key')
    await client.checkConfigurationRestore(id, 'check-key')
    await client.prepareConfigurationRestore(id, 'prepare-key')
    await client.commitConfigurationRestore(id, '9007199254740993', 'commit-key')
    await client.cancelConfigurationRestore(id, 'cancel-key')
    expect(fetcher.mock.calls.map(c => c[0])).toEqual([
      `/api/v3/configuration-backups/${id}/restore-preview`, '/api/v3/configuration-restores',
      `/api/v3/configuration-restores/${id}/check`, `/api/v3/configuration-restores/${id}/prepare`,
      `/api/v3/configuration-restores/${id}/commit`, `/api/v3/configuration-restores/${id}/cancel`,
    ])
    expect(JSON.parse(fetcher.mock.calls[0]![1].body)).toEqual({ use_backup_credentials: false })
    expect(JSON.parse(fetcher.mock.calls[4]![1].body)).toEqual({ generation: '9007199254740993', confirm: true })
    expect(fetcher.mock.calls[4]![1].headers['Idempotency-Key']).toBe('commit-key')
    expect(fetcher.mock.calls[4]![1].headers['X-CSRF-Token']).toBe('restore-csrf')
  })
  it('sends configuration YAML unchanged and encrypted imports as multipart without putting passwords in URLs', async () => {
    const send = vi.fn().mockImplementation(async () => new Response('{}'))
    vi.stubGlobal('fetch', send)
    const client = new ControlV3(), raw = 'format_version: 3\nformat_version: 3\n'
    await client.importConfigurationBackup(raw, 'yaml-original')
    expect(send.mock.calls[0]![1].body).toBe(raw)
    expect(send.mock.calls[0]![1].headers['Content-Type']).toBe('application/yaml')
    const file = new File(['synthetic-age-package'], 'not-a-server-path.age')
    await client.importEncryptedConfigurationBackup(file, 'isolated-import-password', 'import-age')
    expect(send.mock.calls[1]![0]).toBe('/api/v3/configuration-backups/import-age')
    expect(send.mock.calls[1]![1].body).toBeInstanceOf(FormData)
    expect(send.mock.calls[1]![1].body.get('password')).toBe('isolated-import-password')
    expect(send.mock.calls[1]![1].headers['Content-Type']).toBeUndefined()
    expect(send.mock.calls[1]![1].headers['Idempotency-Key']).toBe('import-age')
    expect(() => client.importConfigurationBackup(' ', 'empty')).toThrow('32 MiB')
    expect(() => client.importEncryptedConfigurationBackup(new File([], 'empty'), 'valid-length-password', 'empty')).toThrow('34 MiB')
  })
  it('validates byte-counted export passwords and downloads complete configuration attachments', async () => {
    const send = vi.fn().mockImplementation(async () => new Response('synthetic-age', { headers: { 'Content-Type': 'application/octet-stream', 'Content-Length': '13' } }))
    vi.stubGlobal('fetch', send)
    const client = new ControlV3(), id = 'a'.repeat(64)
    expect(() => client.exportEncryptedConfigurationBackup(id, 'short', 'short')).toThrow('12～1024')
    expect(() => client.exportEncryptedConfigurationBackup(id, 'valid-password', 'different')).toThrow('两次输入一致')
    const blob = await client.exportEncryptedConfigurationBackup(id, '四个汉字', '四个汉字')
    expect(blob.size).toBe(13)
    expect(send.mock.calls[0]![0]).toBe(`/api/v3/configuration-backups/${id}/export-age`)
    expect(JSON.parse(send.mock.calls[0]![1].body)).toEqual({ password: '四个汉字', confirm: '四个汉字' })
    send.mockResolvedValueOnce(new Response('truncated', { headers: { 'Content-Type': 'application/octet-stream', 'Content-Length': '100' } }))
    await expect(client.exportConfigurationBackup(id)).rejects.toMatchObject({ code: 'invalid_export' })
  })
  it('preserves raw backup JSON for strict server parsing and rejects empty or oversized text locally', async () => {
    const send = vi.fn().mockResolvedValue(new Response('{}'))
    vi.stubGlobal('fetch', send)
    const client = new ControlV3(), raw = '{"format_version":1,"format_version":2,"websites":[]}'
    await client.importWebsiteBackupText(raw, 'import-original')
    expect(send.mock.calls[0]![1].body).toBe(raw)
    expect(send.mock.calls[0]![1].headers['Idempotency-Key']).toBe('import-original')
    expect(() => client.importWebsiteBackupText(' ', 'empty')).toThrow('非空')
    expect(() => client.importWebsiteBackupText('中'.repeat(700000), 'large')).toThrow('2 MiB')
    expect(send).toHaveBeenCalledTimes(1)
  })
  it('does not misinterpret an automatic task as an account-owned manual export', async () => {
    vi.stubGlobal('fetch', vi.fn().mockResolvedValue(new Response(JSON.stringify({ kind: 'automatic', job: { status: 'running' } }))))
    await expect(new ControlV3().historyJob('auto-task')).rejects.toMatchObject({ code: 'automatic_history_job' })
  })
  it('binds backup restoration to its preview and deletes only selected backup identities', async () => {
    const send = vi.fn().mockImplementation(async () => new Response(JSON.stringify({})))
    vi.stubGlobal('fetch', send)
    const client = new ControlV3()
    const id = 'a'.repeat(64)
    await client.previewWebsiteBackup(id)
    await client.restoreWebsiteBackup(id, 'preview-token', 'restore-once')
    expect(send.mock.calls[1]![0]).toBe(`/api/v3/website-backups/${id}/restore`)
    expect(JSON.parse(send.mock.calls[1]![1].body)).toEqual({ token: 'preview-token' })
    expect(send.mock.calls[1]![1].headers['Idempotency-Key']).toBe('restore-once')
    await client.deleteWebsiteBackups([id], 'delete-one')
    expect(JSON.parse(send.mock.calls[2]![1].body)).toEqual({ records: [id] })
    expect(() => client.deleteWebsiteBackups([], 'empty')).toThrow('当前页备份')
    expect(() => client.deleteWebsiteBackups([id, id], 'duplicate')).toThrow('当前页备份')
    expect(send).toHaveBeenCalledTimes(3)
  })
  it('keeps configuration deletion scope and confirmation out of query strings and uses the supplied retry key', async () => {
    const send = vi.fn().mockImplementation(async () => new Response('{}'))
    vi.stubGlobal('fetch', send)
    const client = new ControlV3(), records = ['configuration-backup:' + 'a'.repeat(64)]
    await client.previewConfigurationDelete(records)
    await client.deleteConfigurationBackups('b'.repeat(64), 'delete-once')
    expect(send.mock.calls[0]![0]).toBe('/api/v3/configuration-backups/delete-preview')
    expect(JSON.parse(send.mock.calls[0]![1].body)).toEqual({ records })
    expect(send.mock.calls[1]![0]).toBe('/api/v3/configuration-backups/delete')
    expect(JSON.parse(send.mock.calls[1]![1].body)).toEqual({ token: 'b'.repeat(64), confirm: true })
    expect(send.mock.calls[1]![1].headers['Idempotency-Key']).toBe('delete-once')
  })
  it('uses persisted-session csrf and the explicit idempotency key', async () => {
    const send = vi.fn()
      .mockResolvedValueOnce(new Response(JSON.stringify({ username: 'admin', role: 'admin', csrf: 'fixture-csrf' })))
      .mockResolvedValueOnce(new Response(JSON.stringify({ id: 'a', version: 2 })))
    vi.stubGlobal('fetch', send)
    const client = new ControlV3()
    await client.session()
    await client.saveServer({ id: 'a', name: 'A', endpoint: '192.0.2.1:19100', server_name: '192.0.2.1', enabled: true, mode: 'native' }, 1, 'request-one')
    const [path, init] = send.mock.calls[1]!
    expect(path).toBe('/api/v3/servers')
    expect(init.headers['Idempotency-Key']).toBe('request-one')
    expect(init.headers['X-CSRF-Token']).toBe('fixture-csrf')
    expect(JSON.parse(init.body).expected_version).toBe(1)
  })

  it('does not replay writes or mistake service failure for logout', async () => {
    const unauthorized = vi.fn()
    const send = vi.fn().mockResolvedValue(new Response(JSON.stringify({ code: 'unavailable', message: '服务暂不可用' }), { status: 503 }))
    vi.stubGlobal('fetch', send)
    const client = new ControlV3(unauthorized)
    await expect(client.saveServer({ id: 'a', name: 'A', endpoint: '192.0.2.1:19100', server_name: '192.0.2.1', enabled: true, mode: 'native' }, 0, 'request-one')).rejects.toMatchObject({ status: 503 })
    expect(send).toHaveBeenCalledTimes(1)
    expect(unauthorized).not.toHaveBeenCalled()
  })

  it('only reports explicit session authentication failure', async () => {
    const unauthorized = vi.fn()
    vi.stubGlobal('fetch', vi.fn().mockResolvedValue(new Response(JSON.stringify({ code: 'authentication_required', message: '请重新登录' }), { status: 401 })))
    await expect(new ControlV3(unauthorized).session()).rejects.toBeInstanceOf(V3Error)
    expect(unauthorized).toHaveBeenCalledTimes(1)
  })

  it('keeps explicit false and escapes the submitted event filter', async () => {
    const send = vi.fn().mockResolvedValue(new Response(JSON.stringify({ items: [], next_cursor: '', start: 'a', end: 'b' })))
    vi.stubGlobal('fetch', send)
    await new ControlV3().events({ node: '', include_probes: false, q: 'a&b', limit: 20 })
    const path = send.mock.calls[0]![0] as string
    expect(path).toContain('include_probes=false')
    expect(path).toContain('q=a%26b')
    expect(path).not.toContain('node=')
  })

  it('returns an automatic event read failure once for the page scheduler without logging out', async () => {
    const unauthorized = vi.fn()
    const send = vi.fn().mockResolvedValue(new Response(JSON.stringify({ code: 'query_failed', message: '事件暂时不可用' }), { status: 503 }))
    vi.stubGlobal('fetch', send)
    await expect(new ControlV3(unauthorized).events({ include_probes: false }, new AbortController().signal, false)).rejects.toMatchObject({ status: 503 })
    expect(send).toHaveBeenCalledTimes(1)
    expect(unauthorized).not.toHaveBeenCalled()
  })

  it('submits only explicitly selected website versions and never a filter deletion', async () => {
    const send = vi.fn().mockResolvedValue(new Response(JSON.stringify({ deleted: 2, message: '已软删除' })))
    vi.stubGlobal('fetch', send)
    const client = new ControlV3()
    await client.deleteWebsites([{ id: 2, version: 3 }, { id: 7, version: 1 }], 'delete-selected')
    const [path, init] = send.mock.calls[0]!
    expect(path).toBe('/api/v3/websites/delete')
    expect(init.headers['Idempotency-Key']).toBe('delete-selected')
    expect(JSON.parse(init.body)).toEqual({ records: [{ id: 2, version: 3 }, { id: 7, version: 1 }] })
    expect(() => client.deleteWebsites([], 'empty')).toThrow('当前页网站')
    expect(() => client.deleteWebsites([{ id: 1, version: 1 }, { id: 1, version: 2 }], 'duplicate')).toThrow('当前页网站')
    expect(send).toHaveBeenCalledTimes(1)
  })

  it('uses the saved website version for edits and explicit checks', async () => {
    const send = vi.fn().mockImplementation(async () => new Response(JSON.stringify({ id: 7, version: 5 })))
    vi.stubGlobal('fetch', send)
    const client = new ControlV3()
    await client.saveWebsite({ id: 7, name: '网站', url: 'https://example.test/', node: '', keyword: '', slow_alert: false, paused: true }, 4, 'edit-website')
    expect(send.mock.calls[0]![0]).toBe('/api/v3/websites/7')
    expect(send.mock.calls[0]![1].method).toBe('PUT')
    expect(JSON.parse(send.mock.calls[0]![1].body).expected_version).toBe(4)
    await client.checkWebsite(7, 5, 'check-website')
    expect(JSON.parse(send.mock.calls[1]![1].body)).toEqual({ expected_version: 5 })
  })
  it('resumes deployment logs from the exact cursor without exposing write operations', async () => {
    const send = vi.fn().mockImplementation(async () => new Response(JSON.stringify({ items: [], next_cursor: 37, status: 'running' })))
    vi.stubGlobal('fetch', send)
    const client = new ControlV3()
    await client.deploymentLogs('job-1', 0, 100)
    expect(send.mock.calls[0]![0]).toBe('/api/v3/deployments/job-1/logs?after=0&limit=100')
    await client.deploymentLogs('job-1', 37, 100)
    expect(send.mock.calls[1]![0]).toContain('after=37')
    await client.deployments('node-a', '', 20)
    expect(send.mock.calls[2]![0]).toBe('/api/v3/deployments?node=node-a&limit=20')
    await client.deployment('job/1')
    expect(send.mock.calls[3]![0]).toBe('/api/v3/deployments/job%2F1')
    expect(send.mock.calls.every(([, init]) => init.method === 'GET')).toBe(true)
  })

  it('reads current alerts and bounded history without a deletion write', async () => {
    const send = vi.fn().mockImplementation(async () => new Response(JSON.stringify({ items: [], next_cursor: '' })))
    vi.stubGlobal('fetch', send)
    const client = new ControlV3()
    await client.currentAlerts('node-a', 'next-page', 20)
    expect(send.mock.calls[0]![0]).toBe('/api/v3/alerts/current?node=node-a&cursor=next-page&limit=20')
    await client.alertHistory({ phase: 'resolved', limit: 20 })
    expect(send.mock.calls[1]![0]).toBe('/api/v3/alerts/history?phase=resolved&limit=20')
    expect(send.mock.calls.every(([, init]) => init.method === 'GET')).toBe(true)
  })

  it('binds selected history deletion to its preview and explicit confirmation', async () => {
    const send = vi.fn().mockImplementation(async () => new Response(JSON.stringify({})))
    vi.stubGlobal('fetch', send)
    const client = new ControlV3()
    const scope = { categories: ['events'] as const, records: ['event:opaque-key'], include_probes: false }
    await client.previewHistory({ ...scope, categories: [...scope.categories] })
    expect(send.mock.calls[0]![0]).toBe('/api/v3/retention/preview')
    expect(JSON.parse(send.mock.calls[0]![1].body)).toEqual(scope)
    await client.cleanupHistory('private-preview-token', { export_first: false, confirm_without_export: true }, 'delete-once')
    expect(send.mock.calls[1]![0]).toBe('/api/v3/retention/cleanup')
    expect(send.mock.calls[1]![1].headers['Idempotency-Key']).toBe('delete-once')
    expect(JSON.parse(send.mock.calls[1]![1].body)).toEqual({ token: 'private-preview-token', export_first: false, confirm_without_export: true })
    expect(() => client.previewHistory({ categories: ['events'], records: [] })).toThrow('当前页')
    expect(() => client.previewHistory({ categories: ['events'], records: ['one', 'one'] })).toThrow('重复')
    expect(send).toHaveBeenCalledTimes(2)
  })

  it('keeps manual jobs separate from automatic retention and escapes opaque IDs', async () => {
    const send = vi.fn().mockImplementation(async () => new Response(JSON.stringify({})))
    vi.stubGlobal('fetch', send)
    const client = new ControlV3()
    await client.historyJobs('next&cursor', 20)
    expect(send.mock.calls[0]![0]).toBe('/api/v3/retention/jobs?kind=manual&cursor=next%26cursor&limit=20')
    await client.historyJob('job/one')
    expect(send.mock.calls[1]![0]).toBe('/api/v3/retention/jobs/job%2Fone')
    await client.exportHistory('token', 'export-once')
    expect(send.mock.calls[2]![0]).toBe('/api/v3/retention/export')
    expect(send.mock.calls[2]![1].headers['Idempotency-Key']).toBe('export-once')
    await client.notifications({ channel: 'email', state: 'completed', node: 'node-a', cursor: 'delivery-cursor' })
    expect(send.mock.calls[3]![0]).toBe('/api/v3/notifications?channel=email&state=completed&node=node-a&cursor=delivery-cursor')
  })

  it('accepts only complete JSONL downloads and never retries a partial download', async () => {
    const unauthorized = vi.fn()
    const send = vi.fn()
      .mockResolvedValueOnce(new Response('{}\n', { headers: { 'Content-Type': 'application/x-ndjson; charset=utf-8', 'Content-Length': '3' } }))
      .mockResolvedValueOnce(new Response('{}\n', { headers: { 'Content-Type': 'application/x-ndjson', 'Content-Length': '30' } }))
      .mockResolvedValueOnce(new Response('<html>login</html>', { headers: { 'Content-Type': 'text/html' } }))
      .mockResolvedValueOnce(new Response(JSON.stringify({ code: 'authentication_required' }), { status: 401 }))
    vi.stubGlobal('fetch', send)
    const client = new ControlV3(unauthorized)
    expect((await client.downloadHistory('job')).size).toBe(3)
    await expect(client.downloadHistory('job')).rejects.toMatchObject({ code: 'invalid_export' })
    await expect(client.downloadHistory('job')).rejects.toMatchObject({ code: 'invalid_export' })
    expect(unauthorized).not.toHaveBeenCalled()
    await expect(client.downloadHistory('job')).rejects.toMatchObject({ status: 401 })
    expect(unauthorized).toHaveBeenCalledTimes(1)
    expect(send).toHaveBeenCalledTimes(4)
  })

  it('reads bounded audit history without exposing deletion methods', async () => {
    const send = vi.fn().mockResolvedValue(new Response(JSON.stringify({ items: [{ id: '9007199254740993', can_delete: false }], next_cursor: '' })))
    vi.stubGlobal('fetch', send)
    const page = await new ControlV3().audit({ kind: 'legacy-retention_jobs', actor: 'admin', limit: 20 })
    expect(send.mock.calls[0]![0]).toBe('/api/v3/audit?kind=legacy-retention_jobs&actor=admin&limit=20')
    expect(send.mock.calls[0]![1].method).toBe('GET')
    expect(page.items[0]!.id).toBe('9007199254740993')
    expect(page.items[0]!.can_delete).toBe(false)
  })

})

it('keeps settings credentials and signed previews in request bodies, with independent save/apply and idempotency', async () => {
  const send = vi.fn().mockImplementation(async () => new Response('{}'))
  vi.stubGlobal('fetch', send)
  const client = new ControlV3(), input = { action: 'save' as const, expected_generation: '9007199254740993', expected_runtime_version: 5, edit: { secrets: { 'email.password': { action: 'replace' as const, value: 'private-body-only' } } } }
  await client.settings(); await client.previewSettings(input); await client.confirmSettings({ ...input, preview: 'signed-private-preview' }, 'settings-once')
  expect(send.mock.calls.map(c => c[0])).toEqual(['/api/v3/settings', '/api/v3/settings/preview', '/api/v3/settings/confirm'])
  expect(JSON.parse(send.mock.calls[1]![1].body)).toEqual(input); expect(JSON.parse(send.mock.calls[2]![1].body).preview).toBe('signed-private-preview'); expect(send.mock.calls[2]![1].headers['Idempotency-Key']).toBe('settings-once')
  await client.previewSettings({ action: 'apply', expected_generation: '2', expected_runtime_version: 5, edit: {} }); expect(JSON.parse(send.mock.calls[3]![1].body).edit).toEqual({})
})
